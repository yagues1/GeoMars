/** Shared easing curves (kept free of map/DOM imports so state logic stays testable). */
export function easeInOutCubic(t: number) {
  return t < 0.5 ? 4 * t * t * t : 1 - (-2 * t + 2) ** 3 / 2;
}

/** Gentle acceleration out of rest, long soft landing — used for the intro descent. */
export function easeInOutQuint(t: number) {
  return t < 0.5 ? 16 * t ** 5 : 1 - (-2 * t + 2) ** 5 / 2;
}
